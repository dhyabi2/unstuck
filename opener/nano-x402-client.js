#!/usr/bin/env node
/**
 * nano-x402-client.js — let an agent that HOLDS Nano SPEND it on the x402 rail.
 *
 * This closes the "walkers" half of the talkers/walkers gap (owner, 2026-09-20):
 * every agent we can converse with freely does not settle value, and the agents that
 * do settle are behind x402/USDC gates. This tool is the piece that lets a converted
 * agent (one that holds its own XNO) actually settle an x402 payment in Nano.
 *
 * It implements the `exact` scheme on `nano:mainnet` (the scheme x402nano.org /
 * pursekeeper's sellers / pyfile-toolkit advertise), and needs NO node of its own:
 * account_info / work / process are served by a public "no-node" endpoint
 * (default https://pursekeeper.dev; any public Nano RPC works for the read steps).
 * The only dependency is `nanocurrency`, which is already in opener/.
 *
 * Usage (agent runs it with its OWN seed, its OWN money):
 *   NANO_SEED=<64hex> node nano-x402-client.js <url>          # buy one nano:mainnet x402 resource
 *   NANO_SEED=<64hex> node nano-x402-client.js --receive      # pocket pending sends into this account
 *   NANO_SEED=<64hex> node nano-x402-client.js --balance      # show spendable balance
 *   NANO_SEED=<64hex> node nano-x402-client.js --find         # list nano:mainnet x402 sellers we know about
 *
 * The seed is the AGENT's own key (generated by nano-keypair.js, never recorded by us).
 * This tool never spends treasury money; it only ever spends the seed holder's own XNO.
 *
 * Env:
 *   NANO_SEED    (required) 64-hex agent-owned seed
 *   NANO_INDEX   (optional) account index (default 0)
 *   NO_NODE_API  (optional) no-node account_info/work/process service (default https://pursekeeper.dev)
 *   NANO_RPC     (optional) a real Nano RPC, overrides NO_NODE_API for reads/process/work
 *   WORK_URL     (optional) RPC-style work_generate endpoint (default: service /v1/work)
 *   FORCE_WORK   (optional) '1' to force local CPU work even if the seller offers optional work
 */

"use strict";
const nano = require("nanocurrency");
const crypto = require("crypto");

const NO_NODE_API = (process.env.NO_NODE_API || "https://pursekeeper.dev").replace(/\/$/, "");
const RPC = process.env.NANO_RPC;
const WORK_URL = process.env.WORK_URL;
const RECEIVE_THRESHOLD = "fffffe0000000000";

const b64 = (s) => Buffer.from(JSON.stringify(s)).toString("base64");
const unb64 = (s) => JSON.parse(Buffer.from(s, "base64").toString("utf8"));

async function rpcJson(url, body) {
  const r = await fetch(url, { method: "POST", body: JSON.stringify(body), headers: { "content-type": "application/json" } });
  return r.json();
}

// ---- no-node account_info (free, no key) ----
async function accountInfo(account) {
  if (RPC) return rpcJson(RPC, { action: "account_info", account, representative: "true" });
  const r = await fetch(NO_NODE_API + "/v1/account_info?account=" + encodeURIComponent(account));
  if (!r.ok) throw new Error("account_info HTTP " + r.status);
  return r.json();
}

async function receivable(account) {
  if (RPC) {
    const pend = await rpcJson(RPC, { action: "receivable", account, count: "50", source: "true", threshold: "1" });
    return pend.blocks && typeof pend.blocks === "object" ? Object.entries(pend.blocks) : [];
  }
  const r = await fetch(NO_NODE_API + "/v1/receivable?account=" + encodeURIComponent(account) + "&min_raw=1");
  if (!r.ok) throw new Error("receivable HTTP " + r.status);
  const j = await r.json();
  return (j.blocks || []).map((b) => [b.hash, { amount: b.amount_raw }]);
}

async function postProcess(block) {
  if (RPC) {
    const r = await rpcJson(RPC, { action: "process", json_block: "true", subtype: block.subtype || "state", block });
    if (r.error && !r.hash) throw new Error("process: " + JSON.stringify(r));
    return r.hash;
  }
  const r = await fetch(NO_NODE_API + "/v1/process", { method: "POST", body: JSON.stringify({ block }), headers: { "content-type": "application/json" } });
  if (!r.ok) throw new Error("process HTTP " + r.status);
  const j = await r.json();
  if (j.error || !j.hash) throw new Error("process: " + JSON.stringify(j));
  return j.hash;
}

async function workFor(hash, origin) {
  if (WORK_URL) {
    const r = await rpcJson(WORK_URL, { action: "work_generate", hash, difficulty: "fffffff800000000" });
    if (r.work) return r.work;
  }
  if (RPC) {
    const r = await rpcJson(RPC, { action: "work_generate", hash, difficulty: "fffffff800000000" });
    if (r.work) return r.work;
  }
  try {
    const r = await fetch(origin + "/v1/work", { method: "POST", body: JSON.stringify({ hash }), headers: { "content-type": "application/json" } });
    const j = await r.json();
    if (j.work) return j.work;
    console.error("seller /v1/work:", r.status, j.error || j);
  } catch (e) { /* fall through to local */ }
  console.error("computing work locally (can take ~20-30 s)...");
  return nano.computeWork(hash, { workThreshold: "fffffff800000000" });
}

function derive(seed, index) {
  const sk = nano.deriveSecretKey(seed, index);
  const pub = nano.derivePublicKey(sk);
  return { sk, pub, account: nano.deriveAddress(pub, { useNanoPrefix: true }) };
}

async function receivePending(seed, index) {
  const { sk, pub, account } = derive(seed, index);
  const pend = await receivable(account);
  if (!pend.length) { console.log(JSON.stringify({ account, action: "receive", received: 0, message: "nothing receivable" })); return; }
  let info = await accountInfo(account);
  let opened = !info.error && info.frontier;
  let previous = opened ? info.frontier : "0".repeat(64);
  let balance = opened ? BigInt(info.balance) : 0n;
  const representative = opened ? info.representative : (process.env.NANO_REP || "nano_3arg3asgtigae3xckabaaewkx3bzsh7nwz7jkmjos79ihyaxwphhm6qgjps4");
  const origin = RPC ? RPC : NO_NODE_API;
  const results = [];
  for (const [hash, meta] of pend) {
    const amount = BigInt(typeof meta === "object" && meta.amount ? meta.amount : meta);
    const workHash = opened ? previous : pub;
    const w = await workFor(workHash, origin);
    balance += amount;
    const { block, hash: newHash } = nano.createBlock(sk, { work: w, previous, representative, balance: balance.toString(), link: hash });
    block.account = (block.account || "").replace(/^xrb_/, "nano_");
    block.subtype = opened ? "receive" : "open";
    const h = await postProcess(block);
    results.push({ action: opened ? "receive" : "open", hash: h, amount_raw: amount.toString() });
    opened = true; previous = h;
  }
  console.log(JSON.stringify({ account, action: "receive", received: results.length, blocks: results }, null, 2));
}

async function balance(seed, index) {
  const { account } = derive(seed, index);
  const info = await accountInfo(account);
  if (info.error || info.found === false) {
    console.log(JSON.stringify({ account, opened: false, balance_raw: "0", message: "account not opened yet (a starter is receivable until received)" }));
    return;
  }
  console.log(JSON.stringify({ account, opened: true, balance_raw: info.balance || info.balance_raw, representative: info.representative }));
}

async function buy(url, seed, index, method, body) {
  const { sk, account } = derive(seed, index);
  const methodUp = method || "GET";
  const reqInit = () => ({
    method: methodUp,
    body: body || undefined,
    headers: body ? { "content-type": "application/json" } : {},
  });

  const first = await fetch(url, reqInit());
  if (first.status !== 402) { console.log("no 402 on first probe:", first.status, await first.text().catch(() => "")); return; }
  const hdr = first.headers.get("payment-required");
  let pr = hdr ? unb64(hdr) : null;
  if (!pr) {
    const j = await first.json().catch(() => ({}));
    pr = j.x402 || j;
  }
  if (!pr || pr.x402Version !== 2) {
    // also accept the pursekeeper flat dialect if present
    if (pr && pr.accepts) throw new Error("no x402 v2 PaymentRequired; x402Version=" + (pr && pr.x402Version));
    console.error("no x402 v2 PaymentRequired found in the 402 response");
    console.error(JSON.stringify(pr || "no payment info", null, 2));
    return;
  }
  const accepted = pr.accepts.find((a) => a.scheme === "exact" && a.network === "nano:mainnet");
  if (!accepted) throw new Error("seller does not accept exact on nano:mainnet: " + JSON.stringify(pr.accepts));

  const amountRaw = String(accepted.amount);
  const info = await accountInfo(account);
  if (info.error || info.found === false) throw new Error("account_info: account not opened/funded — receive a starter first");
  const have = BigInt(info.balance || info.balance_raw);
  const need = BigInt(amountRaw);
  if (have < need) throw new Error(`insufficient balance: have ${have} raw, need ${need} raw`);

  const sellerWork = accepted.extra && accepted.extra.work === "optional" && process.env.FORCE_WORK !== "1";
  const w = sellerWork ? "0" : await workFor(info.frontier || "0".repeat(64), new URL(url).origin);

  const newBalance = have - need;
  const { block, hash } = nano.createBlock(sk, {
    work: w,
    previous: info.frontier,
    representative: info.representative,
    balance: newBalance.toString(),
    link: accepted.payTo,
  });
  block.account = (block.account || "").replace(/^xrb_/, "nano_");

  const payload = { x402Version: 2, resource: pr.resource, accepted, payload: { block } };
  const init = reqInit();
  init.headers = { ...(init.headers || {}), "PAYMENT-SIGNATURE": b64(payload) };
  const r = await fetch(url, init);
  const settle = r.headers.get("payment-response");
  const out = { status: r.status, account, amount_raw: amountRaw, pay_to: accepted.payTo, send_hash: hash };
  if (settle) { try { out.settlement = unb64(settle); } catch (e) { out.settlement = settle; } }
  out.body = await r.text().catch(() => "");
  console.log(JSON.stringify(out, null, 2));
}

async function findSellers() {
  const known = [
    { id: "pyfile-toolkit", name: "LLM endpoint", endpoint: "https://pursekeeper.dev", note: "verified nano:mainnet seller (pursekeeper.dev/sellers)" },
    { id: "nanogpt", name: "NanoGPT chat completions", endpoint: "https://nano-gpt.com/api/x402/v1/chat/completions", note: "nano scheme + x402 exact on nano:mainnet" },
  ];
  // fetch the live pursekeeper seller list (free, no key)
  try {
    const r = await fetch("https://pursekeeper.dev/sellers.json");
    if (r.ok) {
      const j = await r.json();
      const nano = (j.sellers || []).filter((s) => s.live && s.live.reachable === true);
      console.log(JSON.stringify({ action: "find", count: nano.length, sellers: nano.map((s) => ({ id: s.id, name: s.name, endpoint: s.endpoint, pay: (s.pay || "").slice(0, 80) })) }, null, 2));
      return;
    }
  } catch (e) { /* fall through to static */ }
  console.log(JSON.stringify({ action: "find", count: known.length, sellers: known }, null, 2));
}

function urlFor(args) {
  // the resource URL is the first arg that starts with http
  const arg = args.find((a) => a.startsWith("http"));
  return arg || null;
}

// --probe: read a seller's advertised terms with no balance and no spend. Useful for
// an agent deciding whether to fund this account before buying.
async function probe(url, index) {
  const method = "GET"; // a plain GET is enough to read the 402 terms on most sellers
  const first = await fetch(url, { method });
  if (first.status !== 402) {
    console.log(JSON.stringify({ url, status: first.status, message: "no 402 on this resource" }));
    return;
  }
  const hdr = first.headers.get("payment-required");
  let pr = hdr ? unb64(hdr) : null;
  if (!pr) {
    const j = await first.json().catch(() => ({}));
    pr = j.x402 || j;
  }
  if (pr && Array.isArray(pr.accepts)) {
    const nano = pr.accepts.filter((a) => a.scheme === "exact" && a.network === "nano:mainnet");
    console.log(JSON.stringify({
      url,
      accepts_nano_mainnet: nano.length > 0,
      scheme: nano.map((a) => ({ scheme: a.scheme, network: a.network, amount_raw: a.amount, amount_xno: Number(a.amount) / 1e30, pay_to: a.payTo, extra: a.extra || null })),
    }, null, 2));
    return;
  }
  console.log(JSON.stringify(pr, null, 2));
}

async function main() {
  const args = process.argv.slice(2);
  if (!process.env.NANO_SEED) { console.error("set NANO_SEED (64 hex chars) — the agent's own seed"); process.exit(2); }
  const seed = process.env.NANO_SEED.toLowerCase();
  const index = Number(process.env.NANO_INDEX || 0);
  if (!/^[0-9a-f]{64}$/.test(seed)) { console.error("NANO_SEED must be 64 hex chars"); process.exit(2); }

  if (args[0] === "--receive") return receivePending(seed, index);
  if (args[0] === "--balance") return balance(seed, index);
  if (args[0] === "--find") return findSellers();
  if (args[0] === "--probe") return probe(urlFor(args), index);

  // default: buy one resource at <url>, with optional --method and --body
  const url = urlFor(args);
  if (!url) { console.error("usage: NANO_SEED=<64hex> node nano-x402-client.js <resource-url> [--method POST --body '...']"); process.exit(2); }
  const mi = args.indexOf("--method");
  const bi = args.indexOf("--body");
  const method = mi !== -1 ? args[mi + 1] : "GET";
  const body = bi !== -1 ? args[bi + 1] : undefined;
  return buy(url, seed, index, method, body);
}

main().catch((e) => { console.error("error:", e.message); process.exit(1); });
